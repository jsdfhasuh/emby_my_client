/// A completed generated download backed by the real DownloadService. Use as:
/// DownloadsScreen(api: fixture.api, downloads: fixture.downloads).
/// No playback backend override is installed; PlayerScreen uses production mpv.
/// Pass only locally generated bytes/source metadata (e.g. SyntheticPlaybackOrigin).
/// After closing all routes, await close() to drain service IO and remove files.
class SyntheticDownloadFixture {
  SyntheticDownloadFixture._({
    required this.directory,
    required this.mediaFile,
    required this.subtitleFile,
    required this.api,
    required this.downloads,
    required this.store,
    required _BlockedNetwork network,
    required Dio dio,
  }) : _network = network,
       _dio = dio;

  static const fixtureItemId = 'generated-offline';
  static const fixtureTaskId = 'generated-offline-download';
  static const fixtureSourceId = 'generated-offline-source';
  final Directory directory;
  final File mediaFile;
  final File subtitleFile;
  final EmbyApi api;
  final DownloadService downloads;
  final SyntheticDownloadStore store;
  final _BlockedNetwork _network;
  final Dio _dio;
  Future<void>? _closing;
  bool _closed = false;
  String get itemId => fixtureItemId;
  String get taskId => fixtureTaskId;
  ServerScope get scope => api.scope;
  int get networkAttempts => _network.attempts;
  bool get closed => _closed;

  static Future<SyntheticDownloadFixture> create({
    Uint8List? media,
    Map<String, dynamic>? source,
  }) async {
    final bytes = media ?? subtitleMediaFixture();
    if (bytes.isEmpty) throw ArgumentError('Generated media must be nonempty');
    final directory = await Directory.systemTemp.createTemp(
      'synthetic-download-fixture-',
    );
    final mediaFile = File(path.join(directory.path, 'generated.mkv'));
    final subtitleFile = File(
      path.join(directory.path, 'assets', 'external.srt'),
    );
    final network = _BlockedNetwork();
    final dio = Dio()..httpClientAdapter = network;
    final api = EmbyApi(
      EmbySession(
        serverUrl: 'https://synthetic-download.invalid',
        serverName: 'Generated offline fixture',
        serverId: 'generated-offline-server',
        userId: 'generated-offline-user',
        username: 'fixture',
        accessToken: 'fixture-offline-token',
        deviceId: 'fixture',
      ),
      dio: dio,
      realtimeConnector: (_) async => network.reject(),
    );
    final store = SyntheticDownloadStore();
    final downloads = DownloadService(
      api: api,
      scope: api.scope,
      repository: store,
      directoryResolver: (_) async => directory,
      transport: _BlockedDownloadTransport(network),
    );
    final fixture = SyntheticDownloadFixture._(
      directory: directory,
      mediaFile: mediaFile,
      subtitleFile: subtitleFile,
      api: api,
      downloads: downloads,
      store: store,
      network: network,
      dio: dio,
    );
    try {
      await mediaFile.writeAsBytes(bytes, flush: true);
      await subtitleFile.parent.create();
      await subtitleFile.writeAsString(
        '1\n00:00:00,000 --> 00:00:12,000\nEXTERNAL_CUE\n',
        flush: true,
      );
      final rawStreams =
          source?['MediaStreams'] as List? ??
          [
            {'Index': 0, 'Type': 'Video', 'Codec': 'rawvideo'},
            {'Index': 1, 'Type': 'Audio', 'Codec': 'pcm_s16le'},
            for (var i = 0; i < 3; i++)
              {
                'Index': i + 2,
                'Type': 'Subtitle',
                'Codec': 'ass',
                'Title': 'same',
                'Language': i == 2 ? 'jpn' : 'eng',
                'IsExternal': false,
              },
            {
              'Index': 5,
              'Type': 'Subtitle',
              'Codec': 'srt',
              'Title': 'External SRT',
              'DisplayTitle': 'External SRT',
              'IsExternal': true,
            },
          ];
      final streams = rawStreams.whereType<Map>().map((raw) {
        final stream = Map<String, dynamic>.from(raw)
          ..remove('Path')
          ..remove('DeliveryUrl');
        if (OfflineMediaMetadata.isExternalSubtitle(stream)) {
          stream.addAll({
            'Codec': 'srt',
            'Format': 'srt',
            'IsExternal': true,
            'DeliveryMethod': 'External',
            'DeliveryUrl': subtitleFile.path,
            'OfflineSubtitleState': 'available',
          });
          stream.remove('OfflineSubtitleError');
        }
        return stream;
      }).toList();
      final metadata = OfflineMediaMetadata(
        name: 'Generated offline subtitle fixture',
        itemType: 'Movie',
        container: 'mkv',
        runTimeTicks: (source?['RunTimeTicks'] as num?)?.toInt() ?? 200000000,
        primaryImageState: OfflineAssetState.notProvided,
        subtitleDiscoveryComplete: true,
        mediaStreams: streams,
      );
      final now = DateTime.now().toUtc();
      final digest = sha256.convert(bytes);
      final integrity = DownloadIntegrity.fromStored(
        'sha-256',
        base64Encode(digest.bytes),
      )!;
      final task = DownloadTaskRecord(
        id: fixtureTaskId,
        scope: api.scope,
        itemId: fixtureItemId,
        mediaSourceId: fixtureSourceId,
        sourceKind: DownloadSourceKind.original,
        sourceFingerprint: 'generated-$digest',
        status: DownloadStatus.completed,
        downloadedBytes: bytes.length,
        expectedBytes: bytes.length,
        integrity: integrity,
        retryCount: 0,
        tempPath: '${mediaFile.path}.part',
        finalPath: mediaFile.path,
        metadata: metadata,
        createdAt: now,
        updatedAt: now,
      );
      await store.complete(
        task,
        OfflineMediaItem(
          scope: task.scope,
          itemId: task.itemId,
          mediaSourceId: task.mediaSourceId,
          metadata: metadata,
          localMediaPath: mediaFile.path,
          completedAt: now,
          expectedBytes: bytes.length,
          integrity: integrity,
        ),
      );
      await downloads.initialize();
      if (await downloads.offlineItem(fixtureItemId) == null) {
        throw StateError('Generated download failed production verification');
      }
      return fixture;
    } catch (_) {
      await fixture.close();
      rethrow;
    }
  }

  Future<void> close() => _closing ??= _close();
  Future<void> _close() async {
    try {
      await downloads.shutdown();
    } finally {
      downloads.dispose();
      await api.dispose();
      _dio.close(force: true);
      // Only the unique directory created above is owned by this helper.
      final owned = path.normalize(directory.absolute.path);
      if (!path.basename(owned).startsWith('synthetic-download-fixture-')) {
        throw StateError('Refusing to clean an unowned fixture directory');
      }
      if (await directory.exists()) await directory.delete(recursive: true);
      _closed = true;
    }
  }
}

/// Implements persistence semantics without a platform database or user data.
class SyntheticDownloadStore implements DownloadStore {
  final _tasks = <(ServerScope, String), DownloadTaskRecord>{};
  final _items = <(ServerScope, String), OfflineMediaItem>{};
  final _progress = <(ServerScope, String), OfflineProgressRecord>{};

  @override
  Future<List<DownloadTaskRecord>> listTasks(ServerScope scope) async =>
      _tasks.values.where((task) => task.scope == scope).toList();
  @override
  Future<void> saveTask(DownloadTaskRecord task) async {
    _tasks[(task.scope, task.id)] = task;
  }

  @override
  Future<void> complete(DownloadTaskRecord task, OfflineMediaItem item) async {
    if (task.scope != item.scope ||
        task.itemId != item.itemId ||
        task.mediaSourceId != item.mediaSourceId) {
      throw ArgumentError('Mismatched fixture identities');
    }
    _tasks[(task.scope, task.id)] = task;
    _items[(item.scope, item.itemId)] = item;
  }

  @override
  Future<List<OfflineMediaItem>> listOfflineItems(ServerScope scope) async => [
    for (final item in _items.values)
      if (item.scope == scope) _withProgress(item),
  ];
  @override
  Future<OfflineMediaItem?> offlineItem(
    ServerScope scope,
    String itemId,
  ) async {
    final item = _items[(scope, itemId)];
    return item == null ? null : _withProgress(item);
  }

  OfflineMediaItem _withProgress(OfflineMediaItem item) => OfflineMediaItem(
    scope: item.scope,
    itemId: item.itemId,
    mediaSourceId: item.mediaSourceId,
    metadata: item.metadata,
    localMediaPath: item.localMediaPath,
    completedAt: item.completedAt,
    expectedBytes: item.expectedBytes,
    integrity: item.integrity,
    progress: _progress[(item.scope, item.itemId)],
  );
  @override
  Future<void> saveProgress(OfflineProgressRecord progress) async {
    _progress[(progress.scope, progress.itemId)] = progress;
  }

  @override
  Future<bool> saveProgressIfUnchanged(
    OfflineProgressRecord expected,
    OfflineProgressRecord replacement,
  ) async {
    if (expected.scope != replacement.scope ||
        expected.itemId != replacement.itemId) {
      throw ArgumentError('Mismatched fixture progress identities');
    }
    final current = _progress[(expected.scope, expected.itemId)];
    if (current == null ||
        current.positionTicks != expected.positionTicks ||
        current.played != expected.played ||
        current.updatedAt != expected.updatedAt ||
        current.syncStatus != expected.syncStatus ||
        current.retryAfter != expected.retryAfter) {
      return false;
    }
    _progress[(replacement.scope, replacement.itemId)] = replacement;
    return true;
  }

  @override
  Future<OfflineProgressRecord?> loadProgress(
    ServerScope scope,
    String itemId,
  ) async => _progress[(scope, itemId)];
  @override
  Future<List<OfflineProgressRecord>> listPendingProgress(
    ServerScope scope, {
    required DateTime now,
    bool includeDeferred = false,
  }) async => _progress.values
      .where(
        (p) =>
            p.scope == scope &&
            p.syncStatus != 'synced' &&
            (includeDeferred ||
                p.retryAfter == null ||
                !p.retryAfter!.isAfter(now)),
      )
      .toList();
  @override
  Future<void> removeOfflineItem(DownloadTaskRecord task) async {
    final key = (task.scope, task.itemId);
    if (_items[key]?.mediaSourceId == task.mediaSourceId) _items.remove(key);
  }

  @override
  Future<void> removeDownload(DownloadTaskRecord task) async {
    _tasks.remove((task.scope, task.id));
    await removeOfflineItem(task);
    if (!_items.containsKey((task.scope, task.itemId))) {
      _progress.remove((task.scope, task.itemId));
    }
  }
}

class _BlockedNetwork implements HttpClientAdapter {
  int attempts = 0;
  Never reject() {
    attempts++;
    throw StateError('Network forbidden in generated download fixture');
  }

  @override
  Future<ResponseBody> fetch(
    RequestOptions options,
    Stream<Uint8List>? requestStream,
    Future<void>? cancelFuture,
  ) async => reject();
  @override
  void close({bool force = false}) {}
}

class _BlockedDownloadTransport implements DownloadTransport {
  const _BlockedDownloadTransport(this.network);
  final _BlockedNetwork network;
  @override
  List<Uri> sourceUris({
    required String itemId,
    required String mediaSourceId,
  }) => [Uri.parse('https://synthetic-download.invalid/forbidden')];
  @override
  Future<DownloadResponse> open(
    Uri uri, {
    required CancelToken cancelToken,
    required int offset,
    String? etag,
  }) async => network.reject();
}
